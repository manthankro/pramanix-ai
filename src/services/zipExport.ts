import JSZip from "jszip";
import { ProjectFile, WorkspaceProject } from "../types";

export async function exportProjectZip(
  projectName: string,
  files: ProjectFile[],
  documentation?: { srs?: string; roadmap?: string; vivaGuide?: string; readme?: string }
): Promise<void> {
  const zip = new JSZip();

  // Add source files
  const srcFolder = zip.folder("src");
  files.forEach((file) => {
    if (file.name.startsWith("src/")) {
      srcFolder?.file(file.name.replace(/^src\//, ""), file.content);
    } else {
      zip.file(file.name, file.content);
    }
  });

  // Add documentation
  const docsFolder = zip.folder("docs");
  if (documentation?.srs) {
    docsFolder?.file("SRS_REQUIREMENTS.md", documentation.srs);
  }
  if (documentation?.roadmap) {
    docsFolder?.file("MILESTONES_ROADMAP.md", documentation.roadmap);
  }
  if (documentation?.vivaGuide) {
    docsFolder?.file("VIVA_DEFENSE_GUIDE.md", documentation.vivaGuide);
  }
  if (documentation?.readme) {
    zip.file("README.md", documentation.readme);
  } else {
    zip.file(
      "README.md",
      `# ${projectName}\n\nGenerated with Pramanix - AI Engineering Mentor & Project Workspace.\n`
    );
  }

  // Generate and trigger download
  const blob = await zip.generateAsync({ type: "blob" });
  triggerDownload(blob, `${slugify(projectName)}-project-package.zip`);
}

export async function exportWorkspaceZip(project: WorkspaceProject): Promise<void> {
  const zip = new JSZip();

  // Root details
  zip.file(
    "PROJECT_MANIFEST.json",
    JSON.stringify(
      {
        id: project.id,
        name: project.name,
        domain: project.domain,
        description: project.description,
        connectedRepo: project.connectedRepo,
        taskCount: project.tasks.length,
        exportedAt: new Date().toISOString(),
      },
      null,
      2
    )
  );

  // Notes
  if (project.notes) {
    zip.file("NOTES.md", project.notes);
  }

  // Tasks export
  const tasksMarkdown = `# Tasks for ${project.name}\n\n` +
    project.tasks
      .map((t) => `- [${t.status === "done" ? "x" : " "}] **${t.title}** (${t.status}, priority: ${t.priority})\n  ${t.description || ""}`)
      .join("\n\n");
  zip.file("TASKS.md", tasksMarkdown);

  // Files
  const codeFolder = zip.folder("workspace_files");
  project.files.forEach((f) => {
    codeFolder?.file(f.name, f.content);
  });

  const blob = await zip.generateAsync({ type: "blob" });
  triggerDownload(blob, `${slugify(project.name)}-workspace.zip`);
}

export async function exportProjectBundleZip(project: WorkspaceProject): Promise<void> {
  const zip = new JSZip();

  // 1. Comprehensive Project Metadata for Offline Use
  const metadata = {
    projectId: project.id,
    projectName: project.name,
    domain: project.domain,
    description: project.description,
    connectedRepository: project.connectedRepo || "manthankro/pramanix",
    taskSummary: {
      total: project.tasks.length,
      completed: project.tasks.filter((t) => t.status === "done").length,
      inProgress: project.tasks.filter((t) => t.status === "in_progress").length,
      inReview: project.tasks.filter((t) => t.status === "review").length,
      todo: project.tasks.filter((t) => t.status === "todo").length,
    },
    filesCount: project.files.length,
    offlineUsable: true,
    exportedAt: new Date().toISOString(),
    generator: "Pramanix - AI Engineering Mentor & Project Workspace",
  };

  zip.file("project_metadata.json", JSON.stringify(metadata, null, 2));

  // 2. Offline Development & Execution Guide
  const offlineGuide = `# ${project.name} - Offline Development & Execution Guide

Generated by **Pramanix** for local offline usage.

## Project Summary
- **Project Name:** ${project.name}
- **Domain:** ${project.domain}
- **Connected Repository:** ${project.connectedRepo || "manthankro/pramanix"}
- **Exported Date:** ${new Date().toLocaleDateString()}

## Local Setup & Offline Execution

### 1. Python Environment Setup
\`\`\`bash
# Create local virtual environment
python3 -m venv .venv

# Activate environment
source .venv/bin/activate  # macOS / Linux
# or
.venv\\Scripts\\activate    # Windows

# Run entry point
python3 main.py  # or src/main.py
\`\`\`

### 2. Docker Execution (if applicable)
\`\`\`bash
docker compose up --build
\`\`\`

### 3. Files Included in this Bundle
${project.files.map((f) => `- \`${f.name}\``).join("\n")}
- \`project_metadata.json\` (Project configuration & task metadata)
- \`TASKS.md\` (Complete milestone tasks backlog)
- \`PROJECT_NOTES.md\` (Architectural documentation & formulas)
- \`run_offline.sh\` / \`run_offline.bat\` (Quickstart runners)
`;
  zip.file("OFFLINE_GUIDE.md", offlineGuide);

  // 3. Tasks & Milestones Backlog
  const tasksMarkdown = `# Milestone Tasks Backlog for ${project.name}

${project.tasks
  .map(
    (t, idx) =>
      `### ${idx + 1}. [${t.status === "done" ? "X" : " "}] ${t.title}
- **Status:** ${t.status.toUpperCase()}
- **Priority:** ${t.priority.toUpperCase()}
${t.description ? `- **Description:** ${t.description}` : ""}`
  )
  .join("\n\n")}`;
  zip.file("TASKS.md", tasksMarkdown);

  // 4. Notes & Architecture Documentation
  if (project.notes) {
    zip.file("PROJECT_NOTES.md", project.notes);
  }

  // 5. Source Code & Configuration Files
  project.files.forEach((file) => {
    zip.file(file.name, file.content);
  });

  // 6. Offline launch helper scripts
  zip.file(
    "run_offline.sh",
    `#!/usr/bin/env bash
echo "=========================================="
echo "Starting ${project.name} (Offline Bundle)"
echo "Domain: ${project.domain}"
echo "=========================================="
if [ -f "main.py" ]; then
    python3 main.py
elif [ -f "src/main.py" ]; then
    python3 src/main.py
elif [ -f "package.json" ]; then
    npm start
else
    echo "No standard entrypoint found. Refer to OFFLINE_GUIDE.md."
fi
`
  );

  zip.file(
    "run_offline.bat",
    `@echo off
echo ==========================================
echo Starting ${project.name} (Offline Bundle)
echo Domain: ${project.domain}
echo ==========================================
if exist main.py (
    python main.py
) else if exist src\\main.py (
    python src\\main.py
) else if exist package.json (
    npm start
) else (
    echo No standard entrypoint found. Refer to OFFLINE_GUIDE.md.
)
pause
`
  );

  // Generate and download
  const blob = await zip.generateAsync({
    type: "blob",
    compression: "DEFLATE",
    compressionOptions: { level: 6 },
  });

  triggerDownload(blob, `${slugify(project.name)}-project-bundle.zip`);
}

export function triggerDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/[\s_-]+/g, "-")
    .replace(/^-+|-+$/g, "") || "pramanix-export";
}
