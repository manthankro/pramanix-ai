package com.aistudio.pramanix.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.LazyRow
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.aistudio.pramanix.ui.theme.*

@Composable
fun ProjectBuilderScreen(
    onAddProjectToWorkspace: (String, String, String, String) -> Unit,
    modifier: Modifier = Modifier
) {
    val domains = listOf(
        "AI & Distributed Systems",
        "IoT & Embedded Hardware",
        "Cloud & DevOps Microservices",
        "Robotics & Control Systems",
        "Cybersecurity & Cryptography",
        "Computer Vision & Edge AI"
    )

    var selectedDomain by remember { mutableStateOf(domains[0]) }
    var projectTitle by remember { mutableStateOf("Autonomous Distributed Log Aggregator") }
    var problemStatement by remember {
        mutableStateOf("High-frequency telemetry log loss in containerized clusters under abrupt node failures.")
    }
    var isGenerated by remember { mutableStateOf(false) }

    val generatedNotes = remember(projectTitle, selectedDomain, problemStatement) {
        """# Software Requirements Specification (SRS) - $projectTitle
**Domain:** $selectedDomain
**Author:** Engineering Candidate (Pramanix Guided)

## 1. Problem Statement & Scope
$problemStatement

## 2. Functional Requirements
- **FR-1:** Ingestion pipeline supporting 10,000 events/sec via zero-copy buffer.
- **FR-2:** Deduplication engine using Bloom filters and sliding window caches.
- **FR-3:** Fault recovery checkpointing every 500ms to persistent volume.

## 3. Architecture Blueprint & Milestones
- **M1: Architecture & SRS** - Formalize schema contracts and big-O constraints.
- **M2: Core Subsystems** - Implement queue brokers and containerized workers.
- **M3: Integration & Stress Tests** - Validate throughput and simulate network partitions.
- **M4: Viva Defense** - Prepare slide deck, external examiner rubrics, and source demos.
"""
    }

    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .background(BackgroundDark)
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        item {
            Text(
                text = "Engineering Capstone Project Builder",
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                color = TextPrimary
            )
            Text(
                text = "Turn vague academic requirements into a defense-ready capstone project with automated SRS, milestone breakdown, and starter codebase.",
                style = MaterialTheme.typography.bodyMedium,
                color = TextSecondary,
                modifier = Modifier.padding(top = 4.dp)
            )
        }

        // Domain selection
        item {
            Card(
                colors = CardDefaults.cardColors(containerColor = SurfaceDark),
                shape = RoundedCornerShape(12.dp),
                border = androidx.compose.foundation.BorderStroke(1.dp, BorderDark),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text(
                        text = "1. Select Engineering Domain",
                        style = MaterialTheme.typography.titleSmall,
                        fontWeight = FontWeight.Bold,
                        color = AccentCyan
                    )
                    Spacer(modifier = Modifier.height(10.dp))
                    LazyRow(
                        horizontalArrangement = Arrangement.spacedBy(8.dp),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        items(domains) { domain ->
                            val isSelected = domain == selectedDomain
                            Surface(
                                color = if (isSelected) PrimaryIndigo else SurfaceDarkSubtle,
                                shape = RoundedCornerShape(20.dp),
                                modifier = Modifier
                                    .clip(RoundedCornerShape(20.dp))
                                    .clickable { selectedDomain = domain }
                            ) {
                                Text(
                                    text = domain,
                                    color = if (isSelected) Color.White else TextSecondary,
                                    fontSize = 12.sp,
                                    fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Medium,
                                    modifier = Modifier.padding(horizontal = 14.dp, vertical = 8.dp)
                                )
                            }
                        }
                    }
                }
            }
        }

        // Project details input
        item {
            Card(
                colors = CardDefaults.cardColors(containerColor = SurfaceDark),
                shape = RoundedCornerShape(12.dp),
                border = androidx.compose.foundation.BorderStroke(1.dp, BorderDark),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text(
                        text = "2. Project Title & Problem Statement",
                        style = MaterialTheme.typography.titleSmall,
                        fontWeight = FontWeight.Bold,
                        color = AccentCyan
                    )

                    Spacer(modifier = Modifier.height(10.dp))

                    OutlinedTextField(
                        value = projectTitle,
                        onValueChange = { projectTitle = it },
                        label = { Text("Project Title") },
                        colors = OutlinedTextFieldDefaults.colors(
                            focusedBorderColor = PrimaryIndigo,
                            unfocusedBorderColor = BorderDark,
                            focusedTextColor = TextPrimary,
                            unfocusedTextColor = TextPrimary
                        ),
                        singleLine = true,
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("project_title_input")
                    )

                    Spacer(modifier = Modifier.height(10.dp))

                    OutlinedTextField(
                        value = problemStatement,
                        onValueChange = { problemStatement = it },
                        label = { Text("Problem Statement") },
                        colors = OutlinedTextFieldDefaults.colors(
                            focusedBorderColor = PrimaryIndigo,
                            unfocusedBorderColor = BorderDark,
                            focusedTextColor = TextPrimary,
                            unfocusedTextColor = TextPrimary
                        ),
                        minLines = 3,
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("problem_statement_input")
                    )

                    Spacer(modifier = Modifier.height(14.dp))

                    Button(
                        onClick = { isGenerated = true },
                        colors = ButtonDefaults.buttonColors(containerColor = PrimaryIndigo),
                        shape = RoundedCornerShape(8.dp),
                        modifier = Modifier
                            .fillMaxWidth()
                            .testTag("generate_srs_btn")
                    ) {
                        Icon(Icons.Default.AutoAwesome, contentDescription = null, modifier = Modifier.size(18.dp))
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("Generate SRS & Milestone Blueprint", fontWeight = FontWeight.SemiBold)
                    }
                }
            }
        }

        // Generated Blueprint Preview
        if (isGenerated) {
            item {
                Card(
                    colors = CardDefaults.cardColors(containerColor = SurfaceDarkElevated),
                    shape = RoundedCornerShape(12.dp),
                    border = androidx.compose.foundation.BorderStroke(1.dp, AccentCyan),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Icon(Icons.Default.CheckCircle, contentDescription = null, tint = AccentEmerald)
                            Spacer(modifier = Modifier.width(8.dp))
                            Text(
                                text = "Blueprint Generated Successfully",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = AccentEmerald
                            )
                        }

                        Spacer(modifier = Modifier.height(12.dp))

                        Text(
                            text = generatedNotes,
                            style = MaterialTheme.typography.bodyMedium,
                            color = TextPrimary,
                            lineHeight = 22.sp
                        )

                        Spacer(modifier = Modifier.height(16.dp))

                        Button(
                            onClick = {
                                onAddProjectToWorkspace(
                                    projectTitle,
                                    selectedDomain,
                                    problemStatement,
                                    generatedNotes
                                )
                            },
                            colors = ButtonDefaults.buttonColors(containerColor = AccentEmerald),
                            shape = RoundedCornerShape(8.dp),
                            modifier = Modifier
                                .fillMaxWidth()
                                .testTag("add_to_workspace_btn")
                        ) {
                            Icon(Icons.Default.RocketLaunch, contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(modifier = Modifier.width(8.dp))
                            Text("Deploy to Project Workspace (1-Click)", color = Color.Black, fontWeight = FontWeight.Bold)
                        }
                    }
                }
            }
        }
    }
}
